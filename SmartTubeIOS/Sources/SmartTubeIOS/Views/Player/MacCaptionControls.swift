#if os(macOS)
import SmartTubeIOSCore
import SwiftUI

struct MacCaptionControls: View {
    let vm: PlaybackViewModel
    @Environment(SettingsStore.self) private var store

    private func select(_ track: CaptionTrack?) {
        vm.selectCaption(track)
        store.settings.preferredCaptionLanguage = track?.languageCode
    }

    var body: some View {
        HStack(spacing: 3) {
            Button {
                if vm.selectedCaption != nil { select(nil) }
                else {
                    let language = store.settings.preferredCaptionLanguage ?? Locale.preferredLanguages.first ?? "en"
                    let base = language.split(separator: "-").first.map(String.init) ?? language
                    select(vm.availableCaptions.first(where: { $0.languageCode == language })
                        ?? vm.availableCaptions.first(where: { $0.languageCode.split(separator: "-").first.map(String.init) == base })
                        ?? vm.availableCaptions.first)
                }
            } label: {
                Image(systemName: vm.selectedCaption == nil ? "captions.bubble" : "captions.bubble.fill")
                    .font(.title3).foregroundStyle(vm.selectedCaption == nil ? .white : .yellow)
            }
            .buttonStyle(.plain)
            .disabled(vm.availableCaptions.isEmpty)
            .help(vm.availableCaptions.isEmpty ? "No accessible captions" : "Toggle closed captions")
            .accessibilityLabel("Closed captions")
            .accessibilityValue(vm.availableCaptions.isEmpty ? "Unavailable" : vm.selectedCaption?.name ?? "Off")
            .accessibilityIdentifier("player.captionsToggle")
            Menu {
                Button("Off") { select(nil) }
                ForEach(vm.availableCaptions) { track in
                    Button {
                        select(track)
                    } label: {
                        Label(track.name + (track.isAutoGenerated ? " (auto-generated)" : ""),
                              systemImage: vm.selectedCaption?.id == track.id ? "checkmark" : "text.bubble")
                    }
                }
                if vm.availableCaptions.isEmpty { Text("No accessible captions") }
                if let error = vm.captionsManager.fetchError { Text(error) }
            } label: { Image(systemName: "chevron.down").font(.caption2) }
            .menuStyle(.borderlessButton).fixedSize()
            .help("Caption language")
            .accessibilityLabel("Caption language")
            .accessibilityIdentifier("player.captionLanguage")
        }
        .padding(8).background(.black.opacity(0.4), in: Capsule())
    }
}
#endif
