import AVFoundation
import Foundation
import SmartTubeIOSCore

// MARK: - Caption Track Selection (thin wrapper — logic lives in CaptionsManager)

extension PlaybackViewModel {

    public func selectCaption(_ track: CaptionTrack?) {
        #if os(macOS)
        if player.currentItem === nativeCaptionItem, let group = nativeCaptionGroup {
            player.currentItem?.select(track.flatMap { nativeCaptionOptions[$0.id] }, in: group)
        }
        if let track, nativeCaptionOptions[track.id] != nil {
            captionsManager.selectCaption(nil)
            selectedCaption = track
        } else {
            captionsManager.selectCaption(track, currentTime: currentTime)
        }
        #else
        captionsManager.selectCaption(track, currentTime: currentTime)
        #endif
        // Persist the user's choice so it can be re-applied to the next video.
        // nil means "captions off" and clears the preference.
        settings.preferredCaptionLanguage = track?.languageCode
    }

    func updateCaptionCue(for time: TimeInterval) {
        captionsManager.updateCaptionCue(for: time)
    }

    /// Applies the saved caption language preference to the available tracks.
    /// Call this after `availableCaptions` is populated on video load.
    /// Does nothing when `preferredCaptionLanguage` is nil (captions stay off).
    func autoApplyCaptionPreference(tracks: [CaptionTrack]) {
        guard let code = settings.preferredCaptionLanguage, !code.isEmpty, !tracks.isEmpty else {
            return
        }
        // Exact match first, then BCP-47 prefix match (e.g. "en" matches "en-US").
        let base = code.components(separatedBy: "-").first ?? code
        if let match = tracks.first(where: { $0.languageCode == code })
            ?? tracks.first(where: { $0.languageCode.hasPrefix(base) })
        {
            selectCaption(match)
        }
        // No match: leave captions off rather than forcing a wrong language.
    }
    #if os(macOS)
    /// HLS can carry rolling native captions even when external timed text is absent.
    /// Refresh media selection after every replacement item, preserving the choice.
    func configureNativeCaptions(for item: AVPlayerItem) async {
        let group = try? await item.asset.loadMediaSelectionGroup(for: .legible)
        guard !Task.isCancelled, player.currentItem === item else { return }
        nativeCaptionItem = item
        nativeCaptionGroup = group
        nativeCaptionOptions = [:]
        availableCaptions.removeAll { $0.id.hasPrefix("native:") }
        if let group {
            for (index, option) in group.options.enumerated() {
                let language = option.extendedLanguageTag ?? option.locale?.identifier ?? "und"
                let id = "native:\(language):\(index)"
                nativeCaptionOptions[id] = option
                // Native tracks are selected through AVFoundation, never downloaded.
                availableCaptions.append(CaptionTrack(id: id, baseURL: URL(string: "about:blank")!,
                    name: option.displayName, languageCode: language, isAutoGenerated: false))
            }
        }
        if let selectedCaption, let replacement = availableCaptions.first(where: { $0.id == selectedCaption.id }) {
            if nativeCaptionOptions[replacement.id] != nil { selectCaption(replacement) }
            else if let group { item.select(nil, in: group) }
        } else if selectedCaption == nil {
            if let group { item.select(nil, in: group) }
            autoApplyCaptionPreference(tracks: availableCaptions)
        }
    }
    #endif

}
