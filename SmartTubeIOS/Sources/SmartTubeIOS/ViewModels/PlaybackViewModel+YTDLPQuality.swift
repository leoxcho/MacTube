#if os(macOS)
@preconcurrency import AVFoundation
import SmartTubeIOSCore

extension PlaybackViewModel {
    var ytdlpDownloadHeights: [Int] {
        let available = Set(
            ytdlpStream?.formats.compactMap { $0.hasVideo && $0.ext == "mp4" ? $0.height : nil }
                ?? availableFormats.map(\.height))
        return YTDLPStreamResolver.heights.reversed().filter { available.contains($0) }
    }
    func installYTDLPCatalog(_ stream: YTDLPStreamResolver.Stream) {
        ytdlpStream = stream
        let previousCaption = selectedCaption
        availableCaptions = stream.captionTracks + availableCaptions.filter { $0.id.hasPrefix("native:") }
        if let previousCaption, !previousCaption.id.hasPrefix("native:") {
            if let replacement = stream.captionTracks.first(where: { $0.id == previousCaption.id })
                ?? stream.captionTracks.first(where: { $0.languageCode == previousCaption.languageCode && $0.isAutoGenerated == previousCaption.isAutoGenerated }) {
                if replacement.baseURL != previousCaption.baseURL { selectCaption(replacement) }
            } else {
                selectCaption(nil)
            }
        } else if previousCaption == nil { autoApplyCaptionPreference(tracks: stream.captionTracks) }
        currentVideo?.isLive = stream.isLive
        ytdlpResolvedAt = Date()
        availableFormats = YTDLPStreamResolver.playbackFormats(stream.formats, isLive: stream.isLive).map {
            VideoFormat(
                label: "\($0.height ?? 0)p", width: $0.width ?? 0, height: $0.height ?? 0,
                fps: Int($0.fps ?? 30), mimeType: "video/mp4; codecs=\"\($0.vcodec ?? "")\"",
                url: $0.url.flatMap(URL.init(string:)))
        }
    }
    func ensureYTDLPCatalog() async {
        guard let video = currentVideo, video.localFileURL == nil else { return }
        let request = sessionLease.token
        if let stream = ytdlpStream, Date().timeIntervalSince(ytdlpResolvedAt) < 600 {
            // Primary metadata enrichment may replace the legacy picker list.
            // Restore the cached yt-dlp catalogue without renewing signed URL age.
            let resolvedAt = ytdlpResolvedAt
            installYTDLPCatalog(stream)
            ytdlpResolvedAt = resolvedAt
            return
        }
        toastMessage = "Loading video qualities…"
        do {
            let stream = try await YTDLPStreamResolver().resolve(videoID: video.id)
            guard !Task.isCancelled, sessionLease.isCurrent(request), currentVideo?.id == video.id else { return }
            installYTDLPCatalog(stream)
        } catch { /* Keep existing playback and quality options on metadata failure. */  }
    }
    func selectYTDLPFormat(_ format: VideoFormat?) {
        guard let video = currentVideo, ytdlpStream != nil, !isLoading else { return }
        qualityTask?.cancel()
        itemObserverTask?.cancel()
        nativeOperationID = UUID()
        let operation = nativeOperationID
        let height = format?.height
        let request = sessionLease.token
        qualityTask = Task { [weak self] in
            guard let self else { return }
            let previousSelection = selectedFormat
            let previousItem = player.currentItem
            let wasPlaying = isPlaying
            let rawTime = player.currentTime().seconds
            let savedTime = rawTime.isFinite ? max(0, rawTime) : max(0, currentTime)
            isQualityChangePending = true
            isSwappingItem = true
            do {
                toastMessage = height.map { "Preparing \($0)p…" } ?? "Preparing Auto…"
                let cachedStream = Date().timeIntervalSince(ytdlpResolvedAt) < 600 ? ytdlpStream : nil
                let result = try await startNativePlayback(
                    video: video, preferredHeight: height, startPosition: savedTime,
                    request: request, initialStream: cachedStream,
                    playbackRate: wasPlaying ? Float(settings.playbackSpeed) : 0)
                try Task.checkCancellation()
                guard sessionLease.isCurrent(request), nativeOperationID == operation,
                    currentVideo?.id == video.id else { return }
                installYTDLPCatalog(result.stream)
                nativeActiveFormatID = result.started.format.id
                isAudioOnlyMode = settings.audioOnlyMode || !result.started.format.hasVideo
                // HLS presents a quality ceiling while ABR ramps up from a low initial rendition.
                // Direct/separate selections report the actual decoded stream height.
                let hlsCeiling = Int(result.started.item.preferredMaximumResolution.height)
                let selectedHeight = result.started.format.isHLS && hlsCeiling > 0
                    ? hlsCeiling : result.started.effectiveHeight
                selectedFormat = height.flatMap { _ in availableFormats.first { $0.height == selectedHeight } }
                qualityManager.pendingQualityLabel = selectedFormat?.qualityLabel ?? ""
                qualityManager.perVideoQuality = height.flatMap { AppSettings.VideoQuality.from(height: $0) } ?? .auto
                currentTime = player.currentTime().seconds
                isQualityChangePending = false
                isSwappingItem = false
                retryStatusMessage = ""
                error = nil
                player.rate = wasPlaying ? Float(settings.playbackSpeed) : 0
                isPlaying = wasPlaying
                loadAudioTracks(from: result.started.item)
                monitorYTDLPItem(result.started.item, video: video)
                toastMessage = selectedFormat.map { "\($0.height)p" } ?? "Auto"
            } catch {
                guard sessionLease.isCurrent(request), nativeOperationID == operation,
                    currentVideo?.id == video.id else { return }
                // Keep the previous working item until all bounded alternatives fail.
                player.replaceCurrentItem(with: previousItem)
                if let previousItem {
                    _ = await player.seek(to: CMTime(seconds: savedTime, preferredTimescale: 600))
                    guard sessionLease.isCurrent(request), nativeOperationID == operation,
                        player.currentItem === previousItem else { return }
                    monitorYTDLPItem(previousItem, video: video)
                }
                selectedFormat = previousSelection
                isQualityChangePending = false
                isSwappingItem = false
                retryStatusMessage = ""
                player.rate = wasPlaying ? Float(settings.playbackSpeed) : 0
                isPlaying = wasPlaying
                if !(error is CancellationError) {
                    toastMessage = "Requested quality could not start. Previous quality restored."
                }
            }
        }
    }
}
#endif
